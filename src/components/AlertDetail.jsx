import { X, TriangleAlert } from "lucide-react";
import StatusBadge from "./StatusBadge";

export default function AlertDetail({ alert, onClose }) {
  if (!alert) return null;
  const d = alert.detail;

  return (
    <div className="fixed inset-0 z-40 flex justify-end">
      <div className="absolute inset-0 bg-black/60 backdrop-blur-[1px]" onClick={onClose} />
      <div className="relative w-full max-w-md h-full bg-panel border-l border-panel-border shadow-panel overflow-y-auto animate-in">
        <div className="flex items-center justify-between px-5 h-16 border-b border-panel-border">
          <div>
            <p className="text-[11px] uppercase tracking-wider text-ink-faint">Alert</p>
            <p className="font-display text-sm font-semibold text-ink">{alert.id}</p>
          </div>
          <button onClick={onClose} className="focus-ring rounded-lg p-2 text-ink-muted hover:text-ink hover:bg-panel-alt" aria-label="Close">
            <X className="h-4 w-4" />
          </button>
        </div>

        <div className="p-5 space-y-5">
          <div className="flex items-center justify-between">
            <div>
              <p className="text-xs text-ink-faint">Stock</p>
              <p className="font-display text-xl font-semibold text-ink">{alert.symbol}</p>
            </div>
            <StatusBadge label={alert.risk} />
          </div>

          <div className="grid grid-cols-2 gap-3">
            <div className="nsv-panel-alt rounded-lg p-3">
              <p className="text-[10px] uppercase tracking-wider text-ink-faint mb-1">Type</p>
              <p className="text-sm text-ink">{d.type}</p>
            </div>
            <div className="nsv-panel-alt rounded-lg p-3">
              <p className="text-[10px] uppercase tracking-wider text-ink-faint mb-1">Anomaly Score</p>
              <p className="data-num text-sm text-ink">{alert.anomalyScore.toFixed(2)}</p>
            </div>
          </div>

          <div>
            <p className="text-xs font-medium text-ink-muted mb-2">Detection Evidence</p>
            <div className="nsv-panel-alt rounded-lg divide-y divide-panel-border">
              {[
                ["Historical Volume", d.historicalVolume],
                ["Current Volume", d.currentVolume],
                ["Deviation", d.deviation, d.deviation.startsWith("+") ? "sell" : "buy"],
                ["Historical Volatility", d.historicalVolatility],
                ["Current Volatility", d.currentVolatility],
              ].map(([label, value, tone]) => (
                <div key={label} className="flex items-center justify-between px-3 py-2.5">
                  <span className="text-xs text-ink-muted">{label}</span>
                  <span className={`data-num text-sm ${tone === "sell" ? "text-signal-sell" : tone === "buy" ? "text-signal-buy" : "text-ink"}`}>
                    {value}
                  </span>
                </div>
              ))}
            </div>
          </div>

          <div className="rounded-lg border border-signal-warn/25 bg-signal-warnsoft p-3.5">
            <div className="flex items-center gap-2 mb-1.5">
              <TriangleAlert className="h-4 w-4 text-signal-warn" strokeWidth={1.8} />
              <p className="text-xs font-medium text-signal-warn">AI Assessment — Potential Manipulation Risk: {d.manipulationRisk}</p>
            </div>
            <p className="text-xs text-ink-muted leading-relaxed">{d.assessment}</p>
          </div>

          <p className="text-[10px] text-ink-faint leading-relaxed">
            This surveillance output is generated by an anomaly-detection model for decision support only.
            It does not constitute a confirmed finding of market manipulation.
          </p>
        </div>
      </div>
    </div>
  );
}
